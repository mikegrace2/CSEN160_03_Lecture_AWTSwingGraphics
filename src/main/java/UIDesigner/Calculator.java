	@Override
	public void actionPerformed(ActionEvent e) {
		String command = e.getActionCommand();

		switch (command) {
			case "0": case "1": case "2": case "3": case "4":
			case "5": case "6": case "7": case "8": case "9":
				appendDigit(command);
				break;
			case ".":
				appendDecimalPoint();
				break;
			case "+": case "-": case "*": case "/":
				applyPendingOperator(command);
				break;
			case "=":
				calculateResult();
				break;
			case "C":
				clear();
				break;
			case "⌫":
				backspace();
				break;
			case "%":
				applyPercent();
				break;
			case "±":
				toggleSign();
				break;
			default:
				break;
		}
	}

	private void appendDigit(String digit) {
		if (startNewNumber || display.getText().equals("0")) {
			display.setText(digit);
			startNewNumber = false;
		} else {
			display.setText(display.getText() + digit);
		}
	}

	private void appendDecimalPoint() {
		if (startNewNumber) {
			display.setText("0.");
			startNewNumber = false;
		} else if (!display.getText().contains(".")) {
			display.setText(display.getText() + ".");
		}
	}

	private void applyPendingOperator(String operator) {
		double currentValue = parseDisplay();
		if (pendingOperator != null && !startNewNumber) {
			accumulator = compute(accumulator, currentValue, pendingOperator);
			display.setText(formatNumber(accumulator));
		} else {
			accumulator = currentValue;
		}
		pendingOperator = operator;
		startNewNumber = true;
	}

	private void calculateResult() {
		if (pendingOperator != null) {
			double currentValue = parseDisplay();
			accumulator = compute(accumulator, currentValue, pendingOperator);
			display.setText(formatNumber(accumulator));
			pendingOperator = null;
			startNewNumber = true;
		}
	}

	private void clear() {
		accumulator = 0;
		pendingOperator = null;
		startNewNumber = true;
		display.setText("0");
	}

	private void backspace() {
		String text = display.getText();
		if (text.length() > 1) {
			display.setText(text.substring(0, text.length() - 1));
		} else {
			display.setText("0");
			startNewNumber = true;
		}
	}

	private void applyPercent() {
		display.setText(formatNumber(parseDisplay() / 100));
	}

	private void toggleSign() {
		display.setText(formatNumber(-parseDisplay()));
	}

	private double parseDisplay() {
		try {
			return Double.parseDouble(display.getText());
		} catch (NumberFormatException ex) {
			return 0;
		}
	}

	private double compute(double a, double b, String operator) {
		switch (operator) {
			case "+": return a + b;
			case "-": return a - b;
			case "*": return a * b;
			case "/": return b == 0 ? 0 : a / b;
			default: return b;
		}
	}

	private String formatNumber(double value) {
		if (value == Math.rint(value) && !Double.isInfinite(value)) {
			return String.valueOf((long) value);
		}
		return String.valueOf(value);
	}

